namespace Wagenheimer.MsxAudio.Visualizer;

/// <summary>Tiny 5x7 bitmap font drawn with filled rectangles (no content pipeline needed).</summary>
public static class PixelFont
{
    private const int GlyphWidth = 5;
    private const int GlyphHeight = 7;

    private static readonly Dictionary<char, byte[]> Glyphs = Build();

    public static int Measure(string text, int scale = 1) => text.Length * (GlyphWidth + 1) * scale;

    public static void Draw(SpriteBatch batch, Texture2D pixel, string text, float x, float y, Color color, int scale = 1)
    {
        float cursor = x;
        foreach (char raw in text.ToUpperInvariant())
        {
            if (raw == ' ')
            {
                cursor += (GlyphWidth + 1) * scale;
                continue;
            }

            if (Glyphs.TryGetValue(raw, out var rows))
            {
                for (int r = 0; r < GlyphHeight; r++)
                {
                    byte bits = rows[r];
                    for (int c = 0; c < GlyphWidth; c++)
                    {
                        if ((bits & (1 << (GlyphWidth - 1 - c))) == 0)
                            continue;
                        batch.Draw(pixel,
                            new Rectangle((int)cursor + c * scale, (int)y + r * scale, scale, scale),
                            color);
                    }
                }
            }

            cursor += (GlyphWidth + 1) * scale;
        }
    }

    private static byte[] Rows(string r0, string r1, string r2, string r3, string r4, string r5, string r6)
    {
        return new[]
        {
            Bits(r0), Bits(r1), Bits(r2), Bits(r3), Bits(r4), Bits(r5), Bits(r6),
        };
    }

    private static byte Bits(string row)
    {
        byte value = 0;
        for (int i = 0; i < GlyphWidth; i++)
            if (i < row.Length && row[i] == '#')
                value |= (byte)(1 << (GlyphWidth - 1 - i));
        return value;
    }

